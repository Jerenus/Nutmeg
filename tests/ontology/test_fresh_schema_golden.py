"""Fresh-store schema golden.

Replaces the per-migration DDL/trigger unit tests of the operator_* and discovery
tables (2026-10-08): nothing live writes those tables, so what matters is that the
migration chain keeps producing exactly the same store. A fresh store built by
``run_migrations`` must equal ``golden/fresh_schema.sql`` — every table, index,
trigger and view in ``sqlite_master``, the migration ledger (version, name,
checksum) and the seeded action permissions.

After an intended schema change, regenerate and review the diff:

    NUTMEG_UPDATE_GOLDEN=1 uv run pytest tests/ontology/test_fresh_schema_golden.py
"""
from __future__ import annotations

import os
import sqlite3
from pathlib import Path

import pytest
from sqlalchemy import create_engine

from nutmeg.ontology.repository.migrations import MIGRATIONS, migration_status, run_migrations

GOLDEN = Path(__file__).parent / "golden" / "fresh_schema.sql"
PRODUCTION_COPY = Path(__file__).resolve().parents[2] / ".nutmeg-data" / "ontology" / "ontology.db"


def _dump(database: Path) -> str:
    connection = sqlite3.connect(database)
    try:
        lines = [
            "-- Fresh ontology store: sqlite_master, migration ledger, action permissions.",
            "-- Generated by tests/ontology/test_fresh_schema_golden.py; do not edit by hand.",
            "",
        ]
        for kind, name, sql in connection.execute(
            "SELECT type, name, sql FROM sqlite_master ORDER BY type, name"
        ):
            lines.append(f"-- {kind} {name}")
            lines.append(f"{sql};" if sql else "-- (implicit)")
            lines.append("")
        lines.append("-- schema_migrations: version name checksum")
        lines.extend(
            f"-- {version} {name} {checksum}"
            for version, name, checksum in connection.execute(
                "SELECT version, name, checksum FROM schema_migrations ORDER BY version"
            )
        )
        lines.append("")
        lines.append("-- action_permissions: policy_version action_type actor_role")
        lines.extend(
            f"-- {policy} {action_type} {role}"
            for policy, action_type, role in connection.execute(
                "SELECT policy_version_id, action_type, actor_role FROM action_permissions "
                "ORDER BY 1, 2, 3"
            )
        )
        return "\n".join(lines) + "\n"
    finally:
        connection.close()


def _build(database: Path, migrations=MIGRATIONS) -> Path:
    run_migrations(create_engine(f"sqlite:///{database}"), migrations=migrations)
    return database


def test_fresh_store_matches_golden(tmp_path: Path) -> None:
    actual = _dump(_build(tmp_path / "fresh.db"))
    if os.environ.get("NUTMEG_UPDATE_GOLDEN"):
        GOLDEN.parent.mkdir(parents=True, exist_ok=True)
        GOLDEN.write_text(actual, encoding="utf-8")
    assert actual == GOLDEN.read_text(encoding="utf-8"), (
        "fresh store schema drifted from tests/ontology/golden/fresh_schema.sql "
        "(regenerate with NUTMEG_UPDATE_GOLDEN=1 if the change is intended)"
    )


@pytest.mark.parametrize("start_version", [19, 30])
def test_upgrading_an_older_store_reaches_the_same_schema(
    tmp_path: Path, start_version: int
) -> None:
    database = _build(tmp_path / "old.db", MIGRATIONS[:start_version])
    engine = create_engine(f"sqlite:///{database}")
    report = run_migrations(engine)
    assert report.applied_versions == tuple(range(start_version + 1, len(MIGRATIONS) + 1))
    assert run_migrations(engine).applied_versions == ()
    assert _dump(database) == _dump(_build(tmp_path / "fresh.db"))


@pytest.mark.skipif(not PRODUCTION_COPY.exists(), reason="no local .nutmeg-data store")
def test_local_store_copy_migrates_with_no_drift_and_nothing_pending(tmp_path: Path) -> None:
    """Read-only: the local store (the sandbox copy in a worktree) is backed up into
    tmp_path and the chain runs on that copy — recorded checksums must match and
    nothing may be left pending."""
    source = sqlite3.connect(f"file:{PRODUCTION_COPY}?mode=ro", uri=True)
    copy = sqlite3.connect(tmp_path / "copy.db")
    try:
        source.backup(copy)
    finally:
        source.close()
        copy.close()
    engine = create_engine(f"sqlite:///{tmp_path / 'copy.db'}")
    run_migrations(engine)  # raises MigrationDriftError on any checksum mismatch
    applied = set(migration_status(engine).applied_versions)
    assert [m.version for m in MIGRATIONS if m.version not in applied] == []
    with sqlite3.connect(tmp_path / "copy.db") as connection:
        assert connection.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
